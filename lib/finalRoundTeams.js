// Normalized helper set of Team IDs
export const FINAL_ROUND_ID_SET = new Set(
  FINAL_ROUND_TEAMS.map(t => t.teamId.replace(/[^a-zA-Z0-9]/g, "").toLowerCase()).filter(Boolean)
);

// Normalized helper set of Team Names
export const FINAL_ROUND_NAME_SET = new Set(
  FINAL_ROUND_TEAMS.map(t => t.teamName.trim().toLowerCase()).filter(Boolean)
);

// Fast Map by normalized Team ID
export const FINAL_ROUND_ID_MAP = new Map(
  FINAL_ROUND_TEAMS.map(t => [t.teamId.replace(/[^a-zA-Z0-9]/g, "").toLowerCase(), t])
);

// Fast Map by normalized Team Name
export const FINAL_ROUND_NAME_MAP = new Map(
  FINAL_ROUND_TEAMS.map(t => [t.teamName.trim().toLowerCase(), t])
);

/**
 * Checks whether a team is one of the 49 Final Round Qualifiers
 */
export function isFinalRoundTeam(team) {
  if (!team) return false;
  
  // 1. Check teamIdNo or teamId
  let rawId = team.teamIdNo || team.team_id_no || team.teamId || "";
  if (!rawId || rawId === "N/A") {
    const rawDesc = team.main_idea || team.rawMainIdea || "";
    const m = rawDesc.match(/Team ID:\s*([^\|\]\n]+)/i);
    if (m) rawId = m[1].trim();
  }
  const cleanId = rawId.replace(/[^a-zA-Z0-9]/g, "").toLowerCase();
  if (cleanId && FINAL_ROUND_ID_SET.has(cleanId)) return true;

  // 2. Check teamName
  const cleanName = (team.teamName || team.team_name || "").trim().toLowerCase();
  if (cleanName && FINAL_ROUND_NAME_SET.has(cleanName)) return true;

  return false;
}

/**
 * Returns Final Round metadata for a qualified team (or null if not qualified)
 */
export function getFinalRoundTeamInfo(team) {
  if (!team) return null;
  
  let rawId = team.teamIdNo || team.team_id_no || team.teamId || "";
  if (!rawId || rawId === "N/A") {
    const rawDesc = team.main_idea || team.rawMainIdea || "";
    const m = rawDesc.match(/Team ID:\s*([^\|\]\n]+)/i);
    if (m) rawId = m[1].trim();
  }
  const cleanId = rawId.replace(/[^a-zA-Z0-9]/g, "").toLowerCase();
  if (cleanId && FINAL_ROUND_ID_MAP.has(cleanId)) {
    return FINAL_ROUND_ID_MAP.get(cleanId);
  }

  const cleanName = (team.teamName || team.team_name || "").trim().toLowerCase();
  if (cleanName && FINAL_ROUND_NAME_MAP.has(cleanName)) {
    return FINAL_ROUND_NAME_MAP.get(cleanName);
  }

  return null;
}

/**
 * Filter an array of teams to only include the 49 Final Round Qualifiers
 */
export function filterFinalRoundTeams(teams = []) {
  if (!Array.isArray(teams)) return [];
  return teams.filter(isFinalRoundTeam);
}

